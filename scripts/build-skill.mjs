// Regenerates the hero-txt agent skill from the weekly JSON backup in data/.
//
// The skill is plain files: a hand-written SKILL.md, a query script, and three
// generated artifacts. Keeping the generated ones in git means the skill works
// from a clone with no build step, and every weekly backup leaves a diff of
// what changed in the copy library.
//
// No dependencies: backup.yml runs this without `npm ci`.
//
//   node scripts/build-skill.mjs
//   node scripts/build-skill.mjs --check   # fail if the committed output is stale
//   node scripts/build-skill.mjs --force   # allow a large drop in products

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'data');
const SKILL = join(ROOT, '.opencode', 'skills', 'hero-txt');
const BUNDLE = join(SKILL, 'data', 'products.json');
const CATALOG = join(SKILL, 'references', 'catalog');

const args = new Set(process.argv.slice(2));
const check = args.has('--check');
const force = args.has('--force');

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const slug = (value) =>
  value
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
// Headlines occasionally contain Markdown characters (`banking*`). Escape the
// ones that would change formatting, but leave punctuation and dashes alone.
const md = (value) => String(value).replace(/([\\`*_[\]<>])/g, '\\$1');
const subheadline = (value) => {
  const text = (value || '').trim();
  return !text || text === '/' ? null : text;
};

const categories = readJson(join(DATA, 'categories.json'));
const categoryById = new Map(categories.map((category) => [category.id, category]));
const knownGroups = [...new Set(categories.map((category) => category.group))];

const products = readdirSync(join(DATA, 'products'))
  .filter((file) => file.endsWith('.json'))
  .map((file) => readJson(join(DATA, 'products', file)))
  .map((product) => {
    const category = categoryById.get(product.category);
    const history = (product.history || [])
      .filter((version) => version.headline)
      .map((version) => ({
        date: version.date,
        headline: version.headline.trim(),
        ...(subheadline(version.subheadline) ? { subheadline: subheadline(version.subheadline) } : {}),
      }))
      .sort((a, b) => b.date.localeCompare(a.date));
    return {
      id: product.id,
      name: product.name,
      url: product.url,
      category: product.category,
      categoryName: category?.name || product.category,
      group: category?.group || 'Other',
      history,
    };
  })
  .filter((product) => product.history.length)
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));

// A bad export must not silently shrink the skill to a handful of examples.
if (!check && !force && existsSync(BUNDLE)) {
  const previous = readJson(BUNDLE).count || 0;
  if (products.length < previous / 2) {
    console.error(
      `refusing to build: data/ returned ${products.length} products, the skill holds ${previous}. ` +
        'Check the backup, then rerun with --force if the drop is real.'
    );
    process.exit(1);
  }
}

const ordered = [
  ...categories.flatMap((category) => products.filter((product) => product.category === category.id)),
  ...products.filter((product) => !categoryById.has(product.category)),
];
const latest = ordered.map((product) => product.history[0].date).sort().at(-1) || 'unknown';

const grouped = new Map(knownGroups.map((group) => [group, []]));
for (const product of ordered) {
  if (!grouped.has(product.group)) grouped.set(product.group, []);
  grouped.get(product.group).push(product);
}

const outputs = new Map();

outputs.set(
  BUNDLE,
  json({
    updated: latest,
    count: ordered.length,
    categories: categories.map(({ id, name, group, blurb }) => ({ id, name, group, blurb })),
    products: ordered.map(({ id, name, url, category, categoryName, group, history }) => ({
      id,
      name,
      url,
      category,
      categoryName,
      group,
      history,
    })),
  })
);

const indexLines = [
  '# hero-txt catalog',
  '',
  '<!-- Generated by scripts/build-skill.mjs from data/products/*.json. Do not edit. -->',
  '',
  `${ordered.length} products across ${categories.length} categories. Latest capture ${latest}.`,
  '',
  'Open one group file at a time. For a targeted lookup, `scripts/query.mjs` is cheaper than reading a full catalog.',
  '',
  '| Group | File | Categories | Products |',
  '| ----- | ---- | ---------- | -------- |',
];
for (const [group, items] of grouped) {
  if (!items.length) continue;
  const categoryCount = new Set(items.map((item) => item.category)).size;
  indexLines.push(`| ${md(group)} | [${slug(group)}.md](${slug(group)}.md) | ${categoryCount} | ${items.length} |`);
}
indexLines.push('');
outputs.set(join(CATALOG, 'index.md'), indexLines.join('\n'));

for (const [group, items] of grouped) {
  if (!items.length) continue;
  const dates = items.flatMap((item) => item.history.map((version) => version.date)).sort();
  const lines = [
    `# ${group}`,
    '',
    '<!-- Generated by scripts/build-skill.mjs from data/products/*.json. Do not edit. -->',
    '',
    `${items.length} products, captured ${dates[0]} to ${dates.at(-1)}. Newest version first; earlier versions show repositioning.`,
    '',
  ];
  for (const category of categories.filter((entry) => entry.group === group)) {
    const inCategory = items.filter((item) => item.category === category.id);
    if (!inCategory.length) continue;
    lines.push(`## ${category.name}`, '', `_${category.blurb}_`, '');
    for (const product of inCategory) {
      const [current, ...older] = product.history;
      lines.push(`### ${md(product.name)}`, '');
      lines.push(`**Headline:** ${md(current.headline)}`);
      if (current.subheadline) lines.push(`**Sub-headline:** ${md(current.subheadline)}`);
      lines.push(`**Captured:** ${current.date} · ${product.url}`);
      if (older.length) {
        lines.push('', '**Previous versions:**');
        for (const version of older) {
          lines.push(`- ${version.date} — ${md(version.headline)}${version.subheadline ? ` — ${md(version.subheadline)}` : ''}`);
        }
      }
      lines.push('');
    }
  }
  outputs.set(join(CATALOG, `${slug(group)}.md`), lines.join('\n'));
}

const rel = (path) => relative(ROOT, path);
if (check) {
  const stale = [];
  for (const [path, content] of outputs) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) stale.push(rel(path));
  }
  for (const file of existsSync(CATALOG) ? readdirSync(CATALOG) : []) {
    if (file.endsWith('.md') && !outputs.has(join(CATALOG, file))) stale.push(rel(join(CATALOG, file)));
  }
  if (stale.length) {
    console.error(`skill is stale:\n${stale.map((file) => `  ${file}`).join('\n')}\nRun: npm run skill`);
    process.exit(1);
  }
  console.log(`skill is up to date: ${ordered.length} products, ${categories.length} categories`);
} else {
  for (const [path, content] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  // A renamed group should not leave its old catalog behind.
  for (const file of existsSync(CATALOG) ? readdirSync(CATALOG) : []) {
    const path = join(CATALOG, file);
    if (file.endsWith('.md') && !outputs.has(path)) rmSync(path);
  }
  console.log(
    `skill: ${ordered.length} products, ${categories.length} categories, ${outputs.size} files (latest capture ${latest})`
  );
}
